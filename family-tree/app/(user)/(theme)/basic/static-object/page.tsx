"use client";

import { useCallback, useEffect, useMemo, useState } from "react";
import styles from "./static-object.module.css";

type Tenant = {
  id: string;
  email: string;
  full_name: string | null;
  slug: string;
};

type ContentRecord = {
  id: string;
  tenant_id: string;
  section: string;
  content_type: string;
  title: string | null;
  name: string | null;
  description: string | null;
  body: string | null;
  image_path: string | null;
  desktop_image_path: string | null;
  mobile_image_path: string | null;
  desktop_images?: {
    id: string;
    image_path: string | null;
    image_url?: string | null;
    sort_order: number;
  }[];
  video_path: string | null;
  date_of_birth: string | null;
  year: number | null;
  sort_order: number;
  is_published: boolean;
  image_path_url?: string | null;
  desktop_image_path_url?: string | null;
  mobile_image_path_url?: string | null;
  video_path_url?: string | null;
};

type FormState = {
  section: string;
  content_type: string;
  title: string;
  name: string;
  description: string;
  body: string;
  image_path: string;
  desktop_image_path: string;
  mobile_image_path: string;
  video_path: string;
  date_of_birth: string;
  year: string;
  sort_order: string;
  is_published: boolean;
};

function hasContent(item: any): boolean {
  if (!item || typeof item !== "object" || Array.isArray(item)) {
    return false;
  }

  const hasDesktopImages =
    Array.isArray(item.desktop_images) &&
    item.desktop_images.some(
      (image: any) =>
        typeof image?.image_path === "string" &&
        image.image_path.trim() !== ""
    );

  return (
    hasDesktopImages ||
    [
      "title",
      "name",
      "description",
      "body",
      "image_path",
      "desktop_image_path",
      "mobile_image_path",
      "video_path",
      "date_of_birth",
      "year",
    ].some((key) => {
      const value = item[key];

      return (
        value !== null &&
        value !== undefined &&
        String(value).trim() !== ""
      );
    })
  );
}

/**
 * Converts the JSONB document returned by the API into
 * the ContentRecord[] structure used by the existing UI.
 */
function toContentRecords(document: any): ContentRecord[] {
  const content = document?.content;

  if (!content || typeof content !== "object") {
    return [];
  }

  const records: ContentRecord[] = [];

  function addRecord(
    item: any,
    section: string,
    contentType: string,
    fallbackId: string
  ) {
    // Do not display empty default objects or placeholder records.
    if (!hasContent(item)) return;

    records.push({
      id: item.id || fallbackId,
      tenant_id: document.tenant_id,
      section,
      content_type: contentType,
      title: item.title ?? null,
      name: item.name ?? null,
      description: item.description ?? null,
      body: item.body ?? null,
      image_path: item.image_path ?? null,
      desktop_images: Array.isArray(item.desktop_images)
        ? item.desktop_images
        : item.desktop_image_path
          ? [
              {
                id: "desktop-hero-1",
                image_path: item.desktop_image_path,
                image_url: item.desktop_image_url ?? null,
                sort_order: 1,
              },
            ]
          : [],
      desktop_image_path: item.desktop_image_path ?? null,
      mobile_image_path: item.mobile_image_path ?? null,
      video_path: item.video_path ?? null,
      date_of_birth: item.date_of_birth ?? null,
      year: item.year ?? null,
      sort_order: Number(item.sort_order ?? 0),
      is_published: Boolean(item.is_published),

      // Signed URLs generated by the API.
      image_path_url: item.image_url ?? null,
      desktop_image_path_url: item.desktop_image_url ?? null,
      mobile_image_path_url: item.mobile_image_url ?? null,
      video_path_url: item.video_url ?? null,
    });
  }

  const homepage = content.homepage ?? {};
  const ourFamily = content.our_family ?? {};
  const legacy = content.legacy ?? {};

  // Homepage single-item content.
  addRecord(homepage.hero, "homepage", "hero", "hero");

  addRecord(
    homepage.family_video,
    "homepage",
    "family-video",
    "family-video"
  );

  // Homepage repeatable content.
  if (Array.isArray(homepage.legacy_spot)) {
    homepage.legacy_spot.forEach((item: any, index: number) => {
      addRecord(
        item,
        "homepage",
        "legacy-spot",
        `legacy-spot-${index + 1}`
      );
    });
  }

  if (Array.isArray(homepage.testimonies)) {
    homepage.testimonies.forEach((item: any, index: number) => {
      addRecord(
        item,
        "homepage",
        "testimony",
        `testimony-${index + 1}`
      );
    });
  }

  // Our Family content.
  if (Array.isArray(ourFamily.images)) {
    ourFamily.images.forEach((item: any, index: number) => {
      addRecord(
        item,
        "our-family",
        "family-image",
        `family-image-${index + 1}`
      );
    });
  }

//  // Legacy repeatable Featured Family content.
//     if (Array.isArray(legacy.featured_family)) {
//       legacy.featured_family.forEach((item: any, index: number) => {
//         addRecord(
//           item,
//           "legacy",
//           "featured-family",
//           `featured-family-${index + 1}`
//         );
//       });
//     } else if (legacy.featured_family) {
//       // Backward compatibility with any remaining single-object records.
//       addRecord(
//         legacy.featured_family,
//         "legacy",
//         "featured-family",
//         "featured-family"
//       );
//     }

// Legacy repeatable Featured Family content.
if (Array.isArray(legacy.featured_family)) {
  legacy.featured_family.forEach((item: any, index: number) => {
    addRecord(
      item,
      "legacy",
      "featured-family",
      `featured-family-${index + 1}`
    );
  });
} else if (legacy.featured_family) {
  addRecord(
    legacy.featured_family,
    "legacy",
    "featured-family",
    "featured-family"
  );
}

  // Legacy repeatable timeline content.
  if (Array.isArray(legacy.timeline)) {
    legacy.timeline.forEach((item: any, index: number) => {
      addRecord(
        item,
        "legacy",
        "timeline",
        `timeline-${index + 1}`
      );
    });
  }

  return records;
}

const emptyForm: FormState = {
  section: "homepage",
  content_type: "hero",
  title: "",
  name: "",
  description: "",
  body: "",
  image_path: "",
  desktop_image_path: "",
  mobile_image_path: "",
  video_path: "",
  date_of_birth: "",
  year: "",
  sort_order: "0",
  is_published: false,
};

const sectionTypes: Record<string, { value: string; label: string }[]> = {
  homepage: [
    { value: "hero", label: "Hero images" },
    { value: "family-video", label: "Family video" },
    { value: "testimony", label: "Family testimony" },
    { value: "legacy-spot", label: "Legacy spot" },
  ],
  "our-family": [
    { value: "family-image", label: "Family image" },
  ],
  legacy: [
    { value: "featured-family", label: "Featured family member" },
    { value: "timeline", label: "Family timeline" },
  ],
};

const sectionLabels: Record<string, string> = {
  homepage: "Homepage",
  "our-family": "Our Family",
  legacy: "Legacy",
};

const typeLabels: Record<string, string> = {
  hero: "Hero images",
  "family-video": "Family video",
  testimony: "Family testimony",
  "legacy-spot": "Legacy spot",
  "family-image": "Family image",
  "featured-family": "Featured family member",
  timeline: "Family timeline",
};

export default function StaticObject() {
  const [tenants, setTenants] = useState<Tenant[]>([]);
  const [tenantId, setTenantId] = useState("");
  const [records, setRecords] = useState<ContentRecord[]>([]);
  const [form, setForm] = useState<FormState>(emptyForm);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [activeSection, setActiveSection] = useState("homepage");
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [uploading, setUploading] = useState<string | null>(null);
  const [message, setMessage] = useState("");
  const [error, setError] = useState("");
  const [desktopImages, setDesktopImages] = useState<string[]>([
    "",
    "",
    "",
    "",
  ]);

  const apiFetch = useCallback(
    async (url: string, options?: RequestInit) => {
      const response = await fetch(url, {
        ...options,
        credentials: "include",
        headers: {
          ...(options?.body instanceof FormData
            ? {}
            : { "Content-Type": "application/json" }),
          ...options?.headers,
        },
      });

      const result = await response.json().catch(() => ({}));

      if (!response.ok) {
        throw new Error(result.error || "Something went wrong.");
      }

      return result;
    },
    []
  );

  const loadTenants = useCallback(async () => {
    try {
      setLoading(true);

      const data = await apiFetch("/api/admin/family-site-tenants");

      if (!Array.isArray(data)) {
        throw new Error("The tenants API returned an invalid response.");
      }

      setTenants(data);

      if (data.length > 0) {
        setTenantId((current: string) => current || data[0].id);
      } else {
        setTenantId("");
        setRecords([]);
      }
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to load tenants."
      );
    } finally {
      setLoading(false);
    }
  }, [apiFetch]);

  const loadRecords = useCallback(async () => {
    if (!tenantId) {
      setRecords([]);
      return;
    }

    try {
      setLoading(true);

      const data = await apiFetch(
        `/api/admin/family-site-content?tenantId=${encodeURIComponent(tenantId)}`
      );

      setRecords(toContentRecords(data));
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to load content."
      );
    } finally {
      setLoading(false);
    }
  }, [tenantId, apiFetch]);

  useEffect(() => {
    loadTenants();
  }, [loadTenants]);

  useEffect(() => {
    loadRecords();
  }, [loadRecords]);

  const visibleRecords = useMemo(
    () => records.filter((record) => record.section === activeSection),
    [records, activeSection]
  );

  const selectedTenant = tenants.find(
    (tenant) => tenant.id === tenantId
  );

  function updateForm(
    field: keyof FormState,
    value: string | boolean
  ) {
    setForm((current) => ({
      ...current,
      [field]: value,
    }));
  }

  function resetForm() {
    setDesktopImages(["", "", "", ""]);

    setForm({
      ...emptyForm,
      section: activeSection,
      content_type: sectionTypes[activeSection][0].value,
    });

    setEditingId(null);
  }

  function editRecord(record: ContentRecord) {
    setForm({
      section: record.section,
      content_type: record.content_type,
      title: record.title || "",
      name: record.name || "",
      description: record.description || "",
      body: record.body || "",
      image_path: record.image_path || "",
      desktop_image_path: record.desktop_image_path || "",
      mobile_image_path: record.mobile_image_path || "",
      video_path: record.video_path || "",
      date_of_birth: record.date_of_birth || "",
      year: record.year?.toString() || "",
      sort_order: record.sort_order?.toString() || "0",
      is_published: record.is_published,
    });

    setDesktopImages(
      Array.from({ length: 4 }, (_, index) => {
        const images = record.desktop_images || [];
        return images[index]?.image_path || "";
      })
    );

    setEditingId(record.id);
    setMessage("");
    setError("");

    window.scrollTo({
      top: 0,
      behavior: "smooth",
    });
  }

  async function uploadMedia(
    field: keyof FormState,
    file?: File
  ) {
    if (!file || !tenantId) return;

    try {
      setUploading(field);
      setError("");
      setMessage("");

      const formData = new FormData();

      formData.append("tenantId", tenantId);
      formData.append("section", activeSection);
      formData.append("file", file);

      const result = await apiFetch(
        "/api/admin/family-site-upload",
        {
          method: "POST",
          body: formData,
        }
      );

      updateForm(field, result.path);

      setMessage(`${file.name} uploaded successfully.`);
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Upload failed."
      );
    } finally {
      setUploading(null);
    }
  }

  async function uploadDesktopImage(index: number, file?: File) {
    if (!file || !tenantId) return;

    try {
      const uploadKey = `desktop-image-${index}`;

      setUploading(uploadKey);
      setError("");
      setMessage("");

      const formData = new FormData();

      formData.append("tenantId", tenantId);
      formData.append("section", "homepage");
      formData.append("file", file);

      const result = await apiFetch(
        "/api/admin/family-site-upload",
        {
          method: "POST",
          body: formData,
        }
      );

      setDesktopImages((current) => {
        const updated = [...current];
        updated[index] = result.path;
        return updated;
      });

      setMessage(
        `Desktop hero image ${index + 1} uploaded successfully.`
      );
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Image upload failed."
      );
    } finally {
      setUploading(null);
    }
  }

  async function saveContent(
    event: React.FormEvent<HTMLFormElement>
  ) {
    event.preventDefault();

    if (!tenantId) {
      setError("Please select a tenant.");
      return;
    }

    try {
      setSaving(true);
      setError("");
      setMessage("");

      const existingHero = records.find(
        (record) =>
          record.section === "homepage" &&
          record.content_type === "hero"
      );

      // Preserve existing desktop images when adding the mobile image
      // through a fresh form. When editing, the form state is authoritative.
      const desktopImagesToSave = Array.from(
        { length: 4 },
        (_, index) => {
          const path =
            desktopImages[index] ||
            (!editingId
              ? existingHero?.desktop_images?.[index]?.image_path || ""
              : "");

          return path
            ? {
                id: `desktop-hero-${index + 1}`,
                image_path: path,
                sort_order: index + 1,
              }
            : null;
        }
      ).filter(
        (image): image is NonNullable<typeof image> => image !== null
      );

      const item = {
        title: form.title,
        name: form.name,
        description: form.description,
        body: form.body,
        image_path: form.image_path || null,
        video_path: form.video_path || null,
        date_of_birth: form.date_of_birth || null,
        year: form.year ? Number(form.year) : null,
        sort_order: Number(form.sort_order) || 0,
        is_published: form.is_published,

        // Hero-specific fields: save only for the homepage hero
        ...(activeSection === "homepage" && form.content_type === "hero"
          ? {
              desktop_images: desktopImagesToSave,
              desktop_image_path:
                desktopImagesToSave[0]?.image_path || null,
              mobile_image_path: form.mobile_image_path || null,
            }
          : {}),
      };

      const payload = {
        tenant_id: tenantId,
        section: activeSection,
        content_type: form.content_type,
        item,
        updates: item,
      };

      await apiFetch(
        editingId
          ? `/api/admin/family-site-content/${editingId}`
          : "/api/admin/family-site-content",
        {
          method: editingId ? "PATCH" : "POST",
          body: JSON.stringify(payload),
        }
      );

      setMessage(
        editingId ? "Content updated." : "Content added."
      );

      resetForm();

      await loadRecords();
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to save content."
      );
    } finally {
      setSaving(false);
    }
  }

  async function togglePublish(record: ContentRecord) {
    try {
      setError("");
      setMessage("");

      await apiFetch(
        `/api/admin/family-site-content/${record.id}`,
        {
          method: "PATCH",
          body: JSON.stringify({
            tenant_id: tenantId,
            section: record.section,
            content_type: record.content_type,
            updates: {
              is_published: !record.is_published,
            },
          }),
        }
      );

      setMessage(
        record.is_published
          ? "Content unpublished."
          : "Content published."
      );

      await loadRecords();
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to update status."
      );
    }
  }

  async function deleteRecord(record: ContentRecord) {
    const confirmed = window.confirm(
      "Delete this content item?"
    );

    if (!confirmed) return;

    try {
      setError("");
      setMessage("");

      const params = new URLSearchParams({
        tenantId,
        section: record.section,
        content_type: record.content_type,
      });

      await apiFetch(
        `/api/admin/family-site-content/${record.id}?${params.toString()}`,
        {
          method: "DELETE",
        }
      );

      if (editingId === record.id) {
        resetForm();
      }

      setMessage("Content deleted.");

      await loadRecords();
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to delete content."
      );
    }
  }

  const showImage = [
    "testimony",
    "legacy-spot",
    "family-image",
    "featured-family",
  ].includes(form.content_type);

  const showHeroImages = form.content_type === "hero";
  const showVideo = form.content_type === "family-video";
  const showPersonDetails = form.content_type === "featured-family";
  const showTimeline = form.content_type === "timeline";

  function mediaField(
    label: string,
    field: keyof FormState,
    preview?: string | null,
    accept = "image/jpeg,image/png,image/webp,image/avif"
  ) {
    return (
      <div className={styles.field} key={field}>
        <label>{label}</label>

        <input
          type="file"
          accept={accept}
          disabled={Boolean(uploading)}
          onChange={(event) =>
            uploadMedia(field, event.target.files?.[0])
          }
        />

        {uploading === field && (
          <small className={styles.muted}>
            Uploading...
          </small>
        )}

        {form[field] && (
          <small className={styles.uploaded}>
            Uploaded: {String(form[field]).split("/").pop()}
          </small>
        )}

        {preview && (
          <a href={preview} target="_blank" rel="noreferrer">
            Preview existing media
          </a>
        )}
      </div>
    );
  }

  return (
    <main className={styles.container}>
      <header className={styles.hero}>
        <span className={styles.eyebrow}>THE FAMILY TREE</span>
        <h1>Family Website CMS</h1>
        <p>
          Manage the stories, photographs and history of every family.
        </p>
      </header>

      <section className={styles.workspace}>
        <div className={styles.tenantPanel}>
          <div>
            <label htmlFor="tenant">
              Select family website
            </label>

            <select
              id="tenant"
              value={tenantId}
              onChange={(event) => {
                setTenantId(event.target.value);
                resetForm();
                setRecords([]);
                setMessage("");
                setError("");
              }}
            >
              <option value="">Choose a tenant</option>

              {tenants.map((tenant) => (
                <option key={tenant.id} value={tenant.id}>
                  {tenant.full_name || tenant.email} — {tenant.slug}
                </option>
              ))}
            </select>
          </div>

          {selectedTenant && (
            <div className={styles.tenantDetails}>
              <strong>
                {selectedTenant.full_name || selectedTenant.email}
              </strong>
              <span>{selectedTenant.email}</span>
              <span>/{selectedTenant.slug}</span>
            </div>
          )}
        </div>

        <nav className={styles.tabs}>
          {Object.entries(sectionLabels).map(([value, label]) => (
            <button
              key={value}
              type="button"
              className={
                activeSection === value ? styles.activeTab : ""
              }
              onClick={() => {
                setActiveSection(value);
                setDesktopImages(["", "", "", ""]);

                setForm({
                  ...emptyForm,
                  section: value,
                  content_type: sectionTypes[value][0].value,
                });

                setEditingId(null);
                setMessage("");
                setError("");
              }}
            >
              {label}
            </button>
          ))}
        </nav>

        {message && (
          <div className={styles.success}>{message}</div>
        )}

        {error && (
          <div className={styles.error}>{error}</div>
        )}

        <section className={styles.editor}>
          <div className={styles.sectionHeading}>
            <div>
              <h2>
                {editingId ? "Edit content" : "Add new content"}
              </h2>
              <p>{sectionLabels[activeSection]}</p>
            </div>

            {editingId && (
              <button
                type="button"
                onClick={resetForm}
                className={styles.cancel}
              >
                Cancel editing
              </button>
            )}
          </div>

          <form onSubmit={saveContent}>
            <div className={styles.field}>
              <label htmlFor="contentType">
                Content type
              </label>

              <select
                id="contentType"
                value={form.content_type}
                disabled={Boolean(editingId)}
                onChange={(event) =>
                  updateForm("content_type", event.target.value)
                }
              >
                {sectionTypes[activeSection].map((type) => (
                  <option key={type.value} value={type.value}>
                    {type.label}
                  </option>
                ))}
              </select>
            </div>

            {(showImage ||
              showHeroImages ||
              showVideo ||
              showTimeline) && (
              <div className={styles.field}>
                <label htmlFor="title">Title</label>

                <input
                  id="title"
                  value={form.title}
                  onChange={(event) =>
                    updateForm("title", event.target.value)
                  }
                  placeholder="Enter a title"
                />
              </div>
            )}

            {showHeroImages && (
              <div className={styles.mediaGrid}>
                <div className={styles.field}>
                  <label>Desktop hero images (maximum 4)</label>

                  <div className={styles.mediaGrid}>
                    {Array.from({ length: 4 }).map((_, index) => {
                      const existingRecord = records.find(
                        (record) => record.id === editingId
                      );

                      const preview =
                        existingRecord?.desktop_images?.[index]?.image_url ||
                        (index === 0
                          ? existingRecord?.desktop_image_path_url
                          : null);

                      const uploadKey = `desktop-image-${index}`;

                      return (
                        <div className={styles.field} key={index}>
                          <label>Image {index + 1}</label>

                          <input
                            type="file"
                            accept="image/jpeg,image/png,image/webp,image/avif"
                            disabled={Boolean(uploading)}
                            onChange={(event) =>
                              uploadDesktopImage(
                                index,
                                event.target.files?.[0]
                              )
                            }
                          />

                          {uploading === uploadKey && (
                            <small className={styles.muted}>
                              Uploading...
                            </small>
                          )}

                          {desktopImages[index] && (
                            <small className={styles.uploaded}>
                              Uploaded: {desktopImages[index].split("/").pop()}
                            </small>
                          )}

                          {preview && (
                            <a href={preview} target="_blank" rel="noreferrer">
                              Preview image {index + 1}
                            </a>
                          )}

                          {desktopImages[index] && (
                            <button
                              type="button"
                              onClick={() =>
                                setDesktopImages((current) =>
                                  current.map((path, i) =>
                                    i === index ? "" : path
                                  )
                                )
                              }
                            >
                              Remove image
                            </button>
                          )}
                        </div>
                      );
                    })}
                  </div>
                </div>

                {mediaField(
                  "Mobile hero image",
                  "mobile_image_path",
                  editingId
                    ? records.find((r) => r.id === editingId)
                        ?.mobile_image_path_url
                    : null
                )}
              </div>
            )}

            {showVideo &&
              mediaField(
                "Family video",
                "video_path",
                editingId
                  ? records.find((r) => r.id === editingId)
                      ?.video_path_url
                  : null,
                "video/mp4,video/webm,video/quicktime"
              )}

            {showImage &&
              mediaField(
                "Image",
                "image_path",
                editingId
                  ? records.find((r) => r.id === editingId)
                      ?.image_path_url
                  : null
              )}

            {showPersonDetails && (
              <>
                <div className={styles.field}>
                  <label htmlFor="name">Full name</label>

                  <input
                    id="name"
                    value={form.name}
                    onChange={(event) =>
                      updateForm("name", event.target.value)
                    }
                    placeholder="Family member's name"
                  />
                </div>

                <div className={styles.field}>
                  <label htmlFor="dob">Date of birth</label>

                  <input
                    id="dob"
                    type="date"
                    value={form.date_of_birth}
                    onChange={(event) =>
                      updateForm("date_of_birth", event.target.value)
                    }
                  />
                </div>
              </>
            )}

            {showTimeline && (
              <div className={styles.field}>
                <label htmlFor="year">Year</label>

                <input
                  id="year"
                  type="number"
                  value={form.year}
                  onChange={(event) =>
                    updateForm("year", event.target.value)
                  }
                  placeholder="e.g. 1985"
                />
              </div>
            )}

            {["testimony", "legacy-spot"].includes(
              form.content_type
            ) && (
              <div className={styles.field}>
                <label htmlFor="name">
                  {form.content_type === "testimony"
                    ? "Author / family member"
                    : "Name"}
                </label>

                <input
                  id="name"
                  value={form.name}
                  onChange={(event) =>
                    updateForm("name", event.target.value)
                  }
                />
              </div>
            )}

            {form.content_type !== "hero" &&
              form.content_type !== "family-video" && (
                <div className={styles.field}>
                  <label htmlFor="description">
                    Description
                  </label>

                  <textarea
                    id="description"
                    rows={4}
                    value={form.description}
                    onChange={(event) =>
                      updateForm("description", event.target.value)
                    }
                    placeholder="Write a description..."
                  />
                </div>
              )}

            {form.content_type === "testimony" && (
              <div className={styles.field}>
                <label htmlFor="body">Testimony</label>

                <textarea
                  id="body"
                  rows={6}
                  value={form.body}
                  onChange={(event) =>
                    updateForm("body", event.target.value)
                  }
                  placeholder="Enter the family testimony..."
                />
              </div>
            )}

            <div className={styles.field}>
              <label htmlFor="sortOrder">
                Display order
              </label>

              <input
                id="sortOrder"
                type="number"
                value={form.sort_order}
                onChange={(event) =>
                  updateForm("sort_order", event.target.value)
                }
              />
            </div>

            <label className={styles.publishToggle}>
              <input
                type="checkbox"
                checked={form.is_published}
                onChange={(event) =>
                  updateForm("is_published", event.target.checked)
                }
              />
              Publish this content
            </label>

            <button
              type="submit"
              className={styles.saveButton}
              disabled={
                saving ||
                Boolean(uploading) ||
                !tenantId
              }
            >
              {saving
                ? "Saving..."
                : editingId
                  ? "Update content"
                  : "Save content"}
            </button>
          </form>
        </section>

        <section className={styles.records}>
          <div className={styles.sectionHeading}>
            <div>
              <h2>Existing content</h2>
              <p>
                {visibleRecords.length} item(s) in this section
              </p>
            </div>
          </div>

          {loading ? (
            <p className={styles.empty}>
              Loading content...
            </p>
          ) : visibleRecords.length === 0 ? (
            <p className={styles.empty}>
              No content has been added to this section yet.
            </p>
          ) : (
            <div className={styles.recordsGrid}>
              {visibleRecords.map((record) => {
                const preview =
                  record.image_path_url ||
                  record.desktop_image_path_url ||
                  record.video_path_url;

                return (
                  <article
                    className={styles.recordCard}
                    key={record.id}
                  >
                    {record.desktop_images?.map((image, index) =>
                      image.image_url ? (
                        <img
                          key={image.id || index}
                          src={image.image_url}
                          alt={`Desktop hero image ${index + 1}`}
                        />
                      ) : null
                    )}

                    {record.image_path_url && (
                      <img
                        src={record.image_path_url}
                        alt={
                          record.title ||
                          record.name ||
                          "Family content"
                        }
                      />
                    )}

                    {!record.desktop_images?.length &&
                      record.desktop_image_path_url && (
                        <img
                          src={record.desktop_image_path_url}
                          alt="Desktop hero"
                        />
                      )}

                    {record.mobile_image_path_url && (
                      <img
                        src={record.mobile_image_path_url}
                        alt="Mobile hero"
                      />
                    )}

                    {record.video_path_url && (
                      <video
                        src={record.video_path_url}
                        controls
                      />
                    )}

                    <div className={styles.recordBody}>
                      <span className={styles.recordType}>
                        {typeLabels[record.content_type]}
                      </span>

                      <h3>
                        {record.title ||
                          record.name ||
                          "Untitled content"}
                      </h3>

                      {record.description && (
                        <p>{record.description}</p>
                      )}

                      {record.year && (
                        <p>Year: {record.year}</p>
                      )}

                      <span
                        className={
                          record.is_published
                            ? styles.published
                            : styles.unpublished
                        }
                      >
                        {record.is_published
                          ? "Published"
                          : "Draft"}
                      </span>

                      <div className={styles.actions}>
                        <button
                          type="button"
                          onClick={() => editRecord(record)}
                        >
                          Edit
                        </button>

                        <button
                          type="button"
                          onClick={() => togglePublish(record)}
                        >
                          {record.is_published
                            ? "Unpublish"
                            : "Publish"}
                        </button>

                        <button
                          type="button"
                          className={styles.deleteButton}
                          onClick={() => deleteRecord(record)}
                        >
                          Delete
                        </button>
                      </div>

                      {preview && (
                        <a
                          href={preview}
                          target="_blank"
                          rel="noreferrer"
                        >
                          Open media preview
                        </a>
                      )}
                    </div>
                  </article>
                );
              })}
            </div>
          )}
        </section>
      </section>
    </main>
  );
}
